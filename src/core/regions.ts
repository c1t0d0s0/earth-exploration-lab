function inBox(lon: number, lat: number, b: [number, number, number, number]): boolean {
  return lon >= b[0] && lon <= b[2] && lat >= b[1] && lat <= b[3];
}

export function formatLatLonJa(lon: number, lat: number): string {
  const ns = lat >= 0 ? "北緯" : "南緯";
  const ew = lon >= 0 ? "東経" : "西経";
  return `${ns}${Math.abs(Math.round(lat))}°・${ew}${Math.abs(Math.round(lon))}°`;
}

/** 経度緯度 → 地域名（見つからなければ null） */
export function regionName(lon: number, lat: number): string | null {
  const l = ((((lon + 180) % 360) + 360) % 360) - 180;
  for (const r of REGIONS) if (inBox(l, lat, r.bbox)) return r.name;
  return null;
}

/** 「サハラ砂漠（北緯23°・東経12°）」のような表記 */
export function placeLabel(lon: number, lat: number): string {
  const name = regionName(lon, lat);
  const ll = formatLatLonJa(lon, lat);
  return name ? `${name}（${ll}）` : ll;
}
